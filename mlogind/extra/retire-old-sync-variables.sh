#!/bin/sh
# Retire an /etc/mlogind/variables.toml written by the old theme sync.
#
#   retire-old-sync-variables.sh <etc-file> [<default-file>]
#
# Before 4.5.1, `mlogind sync-theme` copied the last user's
# ~/.config/margo/mlogind-variables.toml byte for byte to
# /etc/mlogind/variables.toml, so that "admin" file was really user-written
# (free-text field titles included). The sync now publishes a validated copy
# under /var/lib/mgreet instead, and mlogind already ignores such a stale file
# as the admin palette; this puts the packaged default back so the admin's
# file is theirs again.
#
# Only a file that starts with the exact three-line header the old sync's
# source carried is touched (mlogind/src/config.rs: OLD_SYNC_HEADER). That
# header said the file was overwritten on every theme change, so no admin edit
# to it ever survived a sync: such a file is provably the old sync's. Anything
# else is the admin's and is left alone. The old file is kept beside it as
# <etc-file>.old-sync (nothing reads it); the default, when given and present,
# is installed in its place, else the file is just moved aside and mlogind
# falls back to its built-in palette (the same as the packaged default).
#
# Run as root by install.sh and the pacman post_upgrade hook. Exit 0 when
# there is nothing to do.
set -eu

etc_file=${1:?usage: retire-old-sync-variables.sh <etc-file> [<default-file>]}
default_file=${2:-}

[ -f "$etc_file" ] || exit 0
[ -L "$etc_file" ] && exit 0

header1="# Generated by margo's matugen — mlogind colour variables."
header2="# Overwritten on every wallpaper/theme change; \`mlogind sync-theme\`"
header3="# copies this into /etc/mlogind/variables.toml for the greeter."

line() { sed -n "${1}p" "$etc_file" | tr -d '\r'; }
[ "$(line 1)" = "$header1" ] || exit 0
[ "$(line 2)" = "$header2" ] || exit 0
[ "$(line 3)" = "$header3" ] || exit 0

mv -f "$etc_file" "$etc_file.old-sync"
restored=""
if [ -n "$default_file" ] && [ -f "$default_file" ]; then
  install -m644 "$default_file" "$etc_file"
  restored=" and restored the packaged default"
fi
echo "mlogind: $etc_file was written by the old \`mlogind sync-theme\` from a user's file;" \
  "moved it to $etc_file.old-sync$restored"
