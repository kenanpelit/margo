#!/usr/bin/env bash
# Tests for mlogind/extra/retire-old-sync-variables.sh. Works on files in a
# temp dir; touches nothing under /etc.
#   ./scripts/test-retire-old-sync-variables.sh
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
script="$root/mlogind/extra/retire-old-sync-variables.sh"
default="$root/mlogind/extra/variables.toml"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

fail=0
check() { # name condition...
    local name="$1"; shift
    if "$@"; then echo "ok   $name"; else echo "FAIL $name"; fail=1; fi
}

header="# Generated by margo's matugen — mlogind colour variables.
# Overwritten on every wallpaper/theme change; \`mlogind sync-theme\`
# copies this into /etc/mlogind/variables.toml for the greeter."

# The header must be the one mlogind's own detection uses.
while IFS= read -r line; do
    check "config.rs carries: ${line:0:40}…" grep -qF "\"$line\"" "$root/mlogind/src/config.rs"
done <<<"$header"

etc="$tmp/variables.toml"

# 1. A file the old sync wrote: moved aside, default restored.
printf '%s\npassword_title = "Type your root password"\n' "$header" >"$etc"
sh "$script" "$etc" "$default" >/dev/null
check "old-sync file is kept as .old-sync" grep -q 'root password' "$etc.old-sync"
check "the packaged default replaces it" cmp -s "$etc" "$default"
rm -f "$etc" "$etc.old-sync"

# 2. CRLF line endings do not hide the header.
printf '%s\r\nbg = "#000000"\r\n' "$(printf '%s' "$header" | sed 's/$/\r/')" >"$etc"
sh "$script" "$etc" "$default" >/dev/null
check "CRLF old-sync file is retired too" test -f "$etc.old-sync"
rm -f "$etc" "$etc.old-sync"

# 3. No default given: moved aside only (mlogind uses its baked palette).
printf '%s\n' "$header" >"$etc"
sh "$script" "$etc" >/dev/null
check "without a default the file is only moved" test ! -e "$etc" -a -f "$etc.old-sync"
rm -f "$etc.old-sync"

# 4. The admin's files are never touched.
for name in shipped-default current-matugen partial-header header-not-first; do
    case "$name" in
        shipped-default) cp "$default" "$etc" ;;
        current-matugen) printf '%s\n' \
            "# Generated by margo's matugen — mlogind colour variables." \
            "# Overwritten on every wallpaper/theme change; \`mlogind sync-theme\`" \
            "# publishes a validated copy as /var/lib/mgreet/variables.toml." \
            'bg = "#000000"' >"$etc" ;;
        partial-header) printf '%s\n' \
            "# Generated by margo's matugen — mlogind colour variables." \
            'bg = "#000000"' >"$etc" ;;
        header-not-first) printf '# mine\n%s\n' "$header" >"$etc" ;;
    esac
    before="$(sha256sum "$etc")"
    sh "$script" "$etc" "$default" >/dev/null
    check "admin file left alone: $name" test "$(sha256sum "$etc")" = "$before" -a ! -e "$etc.old-sync"
    rm -f "$etc"
done

# 5. A symlink is never followed or moved.
printf '%s\n' "$header" >"$tmp/target"
ln -s "$tmp/target" "$etc"
sh "$script" "$etc" "$default" >/dev/null
check "a symlink is left alone" test -L "$etc" -a ! -e "$etc.old-sync"
rm -f "$etc"

# 6. Nothing there: nothing to do.
sh "$script" "$etc" "$default" >/dev/null
check "a missing file is fine" test ! -e "$etc" -a ! -e "$etc.old-sync"

exit "$fail"
