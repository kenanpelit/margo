//! Generates `PAGE_SCOPES`: which settings each Settings page owns, so the
//! page can show "N changed" and reset them with its Defaults button.
//!
//! The scope is read straight from the page sources, so it can't drift from
//! what the page actually writes:
//! - shell settings: every `<param>.a.b.c` field path written inside an
//!   `update_config(|<param>| …)` closure → JSON pointer `/a/b/c`;
//! - shell settings bound through `reactive_settings! { group: g, … => key }`
//!   → `/g/key`;
//! - compositor settings: in a page that edits `config.conf`, every string
//!   literal that is a real margo option (`margo_config::parser::OPTION_KEYS`,
//!   read from its source) → a `config.conf` key.
//!
//! Only the pages listed in `PAGES` get a scope. Pages that edit lists the
//! user built (rules, autostart scripts, per-tag layouts, subscriptions, …)
//! are left out on purpose: "Defaults" there would delete the user's own
//! data.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

