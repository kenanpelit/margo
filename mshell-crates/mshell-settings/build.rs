/// Shell settings that hold data the user created (or live state) rather
/// than a preference with a meaningful default. Never part of a page's
/// Defaults.
const USER_DATA: &[&str] = &[
    "/bars/widgets",
    "/game_mode/active",
    "/calendars/subscriptions",
    "/general/weather_saved_locations",
    "/launcher/autostart_scripts",
    "/notifications/blocklist",
];

fn main() {
    let src = Path::new("src");
    let parser = Path::new("../../margo-config/src/parser.rs");
    println!("cargo:rerun-if-changed={}", parser.display());
    let option_keys = option_keys(
        &std::fs::read_to_string(parser).expect("build.rs: read margo-config parser.rs"),
    );
    let mut out = String::from(
        "/// Generated by build.rs: `(route, shell JSON pointers, config.conf keys)`.\n\
         pub(crate) const PAGE_SCOPES: &[(&str, &[&str], &[&str])] = &[\n",
    );
    let mut tags_out = String::from(
        "/// Generated by build.rs: `(route, row tags)` — every `\"setting:…\"` row\n\
         /// name in the page's sources, checked against `PAGE_SCOPES` in tests.\n\
         #[cfg(test)]\n\
         pub(crate) const PAGE_ROW_TAGS: &[(&str, &[&str])] = &[\n",
    );
    for (route, files) in PAGES {
        let mut shell = BTreeSet::new();
        let mut conf = BTreeSet::new();
        let mut tags = BTreeSet::new();
        for file in *files {
            let path = src.join(file);
            println!("cargo:rerun-if-changed={}", path.display());
            let body = std::fs::read_to_string(&path)
                .unwrap_or_else(|e| panic!("build.rs: read {}: {e}", path.display()));
            shell.extend(shell_paths(&body));
            shell.extend(reactive_paths(&body));
            tags.extend(
                string_literals(&body)
                    .into_iter()
                    .filter_map(|l| l.strip_prefix("setting:"))
                    .map(str::to_string),
            );
            if edits_compositor_conf(&body) {
                conf.extend(conf_keys(&body, &option_keys));
            }
        }
        shell.retain(|p: &String| !USER_DATA.iter().any(|u| is_under(p, u)));
        // A path whose parent is also in scope is covered by the parent.
        let all = shell.clone();
        shell.retain(|p| !all.iter().any(|q| q != p && is_under(p, q)));
        if !tags.is_empty() {
            let _ = writeln!(
                tags_out,
                "    ({route:?}, &[{}]),",
                tags.iter()
                    .map(|s| format!("{s:?}"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        if shell.is_empty() && conf.is_empty() {
            continue;
        }
        let list = |set: &BTreeSet<String>| {
            set.iter()
                .map(|s| format!("{s:?}"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let _ = writeln!(
            out,
            "    ({route:?}, &[{}], &[{}]),",
            list(&shell),
            list(&conf)
        );
    }
    out.push_str("];\n");
    tags_out.push_str("];\n");
    out.push_str(&tags_out);
    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("page_scopes.rs");
    std::fs::write(dest, out).expect("build.rs: write page_scopes.rs");
    println!("cargo:rerun-if-changed=build.rs");
}

/// `p` equals `prefix` or lies below it (segment boundary).
fn is_under(p: &str, prefix: &str) -> bool {
    p == prefix || p.strip_prefix(prefix).is_some_and(|r| r.starts_with('/'))
}

fn is_ident(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

/// Field paths written inside `update_config(|param| …)` closures.
fn shell_paths(body: &str) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    let bytes = body.as_bytes();
    let mut from = 0;
    while let Some(at) = body[from..].find("update_config(") {
        let open = from + at + "update_config".len();
        from = open + 1;
        let Some(close) = matching_paren(bytes, open) else {
            continue;
        };
        let call = &body[open + 1..close];
        // `|param|` or `move |param|`
        let Some(bar) = call.find('|') else { continue };
        let Some(end) = call[bar + 1..].find('|') else {
            continue;
        };
        let param = call[bar + 1..bar + 1 + end].trim();
        let param = param.split(':').next().unwrap_or("").trim();
        if param.is_empty() || !param.bytes().all(is_ident) {
            continue;
        }
        let closure = &call[bar + 1 + end + 1..];
        found.extend(field_paths(closure, param));
    }
    found
}

/// Every `param.a.b.c` in `text` as `/a/b/c`, stopping at a method call.
fn field_paths(text: &str, param: &str) -> Vec<String> {
    let mut paths = Vec::new();
    let bytes = text.as_bytes();
    let needle = format!("{param}.");
    let mut from = 0;
    while let Some(at) = text[from..].find(&needle) {
        let start = from + at;
        from = start + needle.len();
        if start > 0 && (is_ident(bytes[start - 1]) || bytes[start - 1] == b'.') {
            continue;
        }
        let mut segs: Vec<&str> = Vec::new();
        let mut i = start + param.len();
        while i < bytes.len() && bytes[i] == b'.' {
            let s = i + 1;
            let mut e = s;
            while e < bytes.len() && is_ident(bytes[e]) {
                e += 1;
            }
            if e == s {
                break;
            }
            let seg = &text[s..e];
            // `.foo(` / `.foo::<` is a method call, not a field.
            let next = text[e..].trim_start();
            if next.starts_with('(') || next.starts_with("::") {
                break;
            }
            // Tuple index or numeric segment: stop at the field holding it.
            if seg.as_bytes()[0].is_ascii_digit() {
                break;
            }
            segs.push(seg);
            i = e;
        }
        if !segs.is_empty() {
            paths.push(format!("/{}", segs.join("/")));
        }
    }
    paths
}

/// Index of the `)` closing the `(` at `open`, skipping string literals.
fn matching_paren(bytes: &[u8], open: usize) -> Option<usize> {
    let mut depth = 0usize;
    let mut i = open;
    let mut in_str = false;
    while i < bytes.len() {
        let b = bytes[i];
        if in_str {
            if b == b'\\' {
                i += 1;
            } else if b == b'"' {
                in_str = false;
            }
        } else {
            match b {
                b'"' => in_str = true,
                b'(' => depth += 1,
                b')' => {
                    depth -= 1;
                    if depth == 0 {
                        return Some(i);
                    }
                }
                _ => {}
            }
        }
        i += 1;
    }
    None
}

/// Does this page write margo's `config.conf`?
fn edits_compositor_conf(body: &str) -> bool {
    body.contains("compositor_conf") || body.contains("\"config.conf\"")
}

/// The string literals of `pub const OPTION_KEYS: &[&str] = &[ … ];`.
fn option_keys(parser: &str) -> BTreeSet<String> {
    let start = parser
        .find("pub const OPTION_KEYS")
        .expect("build.rs: OPTION_KEYS not found in margo-config parser.rs");
    let body = &parser[start..];
    let open = body.find("= &[").expect("OPTION_KEYS array") + 4;
    let close = open + body[open..].find("];").expect("OPTION_KEYS end");
    string_literals(&body[open..close])
        .into_iter()
        .map(str::to_string)
        .collect()
}

/// Every `"…"` literal (no escapes needed for identifiers).
fn string_literals(text: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut rest = text;
    while let Some(s) = rest.find('"') {
        let after = &rest[s + 1..];
        let Some(e) = after.find('"') else { break };
        out.push(&after[..e]);
        rest = &after[e + 1..];
    }
    out
}

/// `config.conf` keys the page mentions: string literals that are margo
/// options.
fn conf_keys(body: &str, option_keys: &BTreeSet<String>) -> BTreeSet<String> {
    string_literals(body)
        .into_iter()
        .filter(|l| option_keys.contains(*l))
        .map(str::to_string)
        .collect()
}

/// `reactive_settings! { group: g, fields { A => f: T => key, … } clamped { … } }`
/// → `/g/key` for every bound field.
fn reactive_paths(body: &str) -> Vec<String> {
    let mut out = Vec::new();
    let Some(at) = body.find("reactive_settings! {") else {
        return out;
    };
    let block = &body[at..];
    let block = &block[..block.find("\n}").unwrap_or(block.len())];
    let Some(g) = block.find("group:") else {
        return out;
    };
    let group: String = block[g + 6..]
        .trim_start()
        .bytes()
        .take_while(|b| is_ident(*b))
        .map(char::from)
        .collect();
    for line in block.lines() {
        // `Base => field: Type => key` or `… => key in lo ..= hi`
        let parts: Vec<&str> = line.split("=>").collect();
        if parts.len() != 3 {
            continue;
        }
        let key: String = parts[2]
            .trim_start()
            .bytes()
            .take_while(|b| is_ident(*b))
            .map(char::from)
            .collect();
        if !key.is_empty() {
            out.push(format!("/{group}/{key}"));
        }
    }
    out
}
