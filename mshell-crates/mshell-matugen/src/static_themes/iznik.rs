/// İznik coral-red tertiary (it also feeds the floating-window border) and
/// warm ivory text instead of a cold white. Manganese lavender and glaze
/// gold fill the base16 accents; error is a raspberry kept apart from the
/// coral so a warning never reads as decoration.
